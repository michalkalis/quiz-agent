// Copies the brand assets from the website (the single source of truth) into
// this app: Rethink Sans into public/brand/, the mascot master split into a
// static body and the animated eyes. Runs on `npm install`; both outputs are
// gitignored so the website files stay the only copy in git.
import {copyFileSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const site = path.resolve(app, '../website/src');

mkdirSync(path.join(app, 'public/brand'), {recursive: true});
for (const f of ['rethink-sans-latin.woff2', 'rethink-sans-latin-ext.woff2']) {
	copyFileSync(path.join(site, f), path.join(app, 'public/brand', f));
}

const svg = readFileSync(path.join(site, 'mascot.svg'), 'utf8');
const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
// The pupils (dark circles on the eye whites) are drawn by Monkey.tsx so they
// can blink and look around; everything before them is the static head.
const PUPIL = '<circle cx="81" cy="103" r="9.5" fill="#2B1A12"/>';
const NOSE = '<ellipse cx="93" cy="141"';
const cut = inner.indexOf(PUPIL);
const nose = inner.indexOf(NOSE);
if (!viewBox || cut < 0 || nose < cut) {
	throw new Error('mascot.svg changed shape: update the PUPIL/NOSE anchors in sync-brand.mjs and Monkey.tsx');
}
mkdirSync(path.join(app, 'src/brand'), {recursive: true});
writeFileSync(
	path.join(app, 'src/brand/mascot-parts.ts'),
	`// GENERATED by scripts/sync-brand.mjs from apps/website/src/mascot.svg. Do not edit.\n` +
		`export const MASCOT_VIEWBOX = ${JSON.stringify(viewBox)};\n` +
		`export const MASCOT_BODY = ${JSON.stringify(inner.slice(0, cut))};\n` +
		`export const MASCOT_FACE = ${JSON.stringify(inner.slice(nose))};\n`,
);
console.log('social-studio: brand assets synced');
